def _plain_text(markdown_text):
    text = re.sub(r"```.*?```", " ", markdown_text, flags=re.S)
    text = re.sub(r"[#>*_`\\-]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _make_summary(content, query, max_len=120):
    text = _plain_text(content)
    query_lower = query.lower()
    text_lower = text.lower()
    pos = text_lower.find(query_lower)
    if pos < 0:
        return text[:max_len] + ("..." if len(text) > max_len else "")
    start = max(0, pos - 35)
    end = min(len(text), pos + max_len - 20)
    prefix = "..." if start > 0 else ""
    suffix = "..." if end < len(text) else ""
    return f"{prefix}{text[start:end]}{suffix}"


def search_help(query):
    """搜索帮助内容，返回主题、摘要和匹配分数"""
    results = []
    query = query.strip().lower()
    if not query:
        return results
    
    for key, value in HELP_MANUAL.items():
        title = value['title']
        content = value['content']
        title_matches = title.lower().count(query)
        content_matches = content.lower().count(query)
        if title_matches or content_matches:
            score = title_matches * 5 + content_matches
            results.append((key, title, value['icon'], _make_summary(content, query), score))
    
    return sorted(results, key=lambda item: item[4], reverse=True)
